export class TriviaGame {
  constructor(containerEl, options = {}) {
    this.container = containerEl;
    this.lang = options.lang || "bn";
    this.currentQuestions = [];
    this.currentIndex = 0;
    this.score = 0;
    this.hasAnswered = false;

    this.renderIntro();
  }

  setLang(lang) {
    this.lang = lang;
    if (this.currentQuestions.length > 0 && this.currentIndex < this.currentQuestions.length) {
      this.renderQuestion();
    } else {
      this.renderIntro();
    }
  }

  start() {
    // Shuffle and pick 5 questions
    const shuffled = [...TRIVIA_QUESTIONS].sort(() => 0.5 - Math.random());
    this.currentQuestions = shuffled.slice(0, 5);
    this.currentIndex = 0;
    this.score = 0;
    this.hasAnswered = false;
    this.renderQuestion();
  }

  renderIntro() {
    if (!this.container) return;
    const isBn = this.lang === 'bn';

    this.container.innerHTML = `
      <div class="trivia-box">
        <div class="trivia-icon">🎯</div>
        <h3>${isBn ? 'খাবার চেনার মজার কুইজ' : 'Bangladesh Food Trivia Challenge'}</h3>
        <p>${isBn 
          ? 'বাংলাদেশের ৬৪ জেলার বিখ্যাত সব ঐতিহ্যবাহী খাবার ও বিশেষত্ব সম্পর্কে আপনি কতটা জানেন? ৫টি দ্রুত প্রশ্নে নিজের শিকড় পরখ করে নিন!' 
          : 'How well do you know the iconic dishes and culinary roots of Bangladesh? Test your knowledge with 5 quick questions!'}</p>
        <button type="button" class="btn-trivia-start">${isBn ? 'কুইজ শুরু করুন ➔' : 'Start Quiz ➔'}</button>
      </div>
    `;

    this.container.querySelector('.btn-trivia-start').addEventListener('click', () => this.start());
  }

  renderQuestion() {
    if (!this.container) return;
    const isBn = this.lang === 'bn';
    const qData = this.currentQuestions[this.currentIndex];
    const total = this.currentQuestions.length;
    this.hasAnswered = false;

    const questionText = isBn ? qData.qBn : qData.qEn;
    const options = isBn ? qData.optsBn : qData.optsEn;

    this.container.innerHTML = `
      <div class="trivia-box active">
        <div class="trivia-top-bar">
          <span class="trivia-counter">${isBn ? `প্রশ্ন ${this.currentIndex + 1} / ${total}` : `Question ${this.currentIndex + 1} of ${total}`}</span>
          <span class="trivia-score-badge">🏆 ${isBn ? `স্কোর: ${this.score}` : `Score: ${this.score}`}</span>
        </div>

        <div class="trivia-progress-bar">
          <div class="tpb-fill" style="width: ${((this.currentIndex + 1) / total) * 100}%"></div>
        </div>

        <h4 class="trivia-q-text">${questionText}</h4>

        <div class="trivia-options-grid">
          ${options.map((opt, i) => `
            <button type="button" class="trivia-opt-btn" data-index="${i}">
              <span class="opt-prefix">${['A', 'B', 'C', 'D'][i]}</span>
              <span class="opt-text">${opt}</span>
            </button>
          `).join('')}
        </div>

        <div class="trivia-fact-box" hidden></div>

        <div class="trivia-actions" hidden>
          <button type="button" class="btn-trivia-next">${isBn ? 'পরবর্তী প্রশ্ন ➔' : 'Next Question ➔'}</button>
        </div>
      </div>
    `;

    const optButtons = this.container.querySelectorAll('.trivia-opt-btn');
    optButtons.forEach(btn => {
      btn.addEventListener('click', () => {
        if (this.hasAnswered) return;
        const selectedIndex = parseInt(btn.dataset.index, 10);
        this.checkAnswer(selectedIndex, qData, optButtons);
      });
    });

    const nextBtn = this.container.querySelector('.btn-trivia-next');
    if (nextBtn) {
      nextBtn.addEventListener('click', () => {
        if (this.currentIndex + 1 < total) {
          this.currentIndex++;
          this.renderQuestion();
        } else {
          this.renderResult();
        }
      });
    }
  }

  checkAnswer(chosenIdx, qData, optButtons) {
    this.hasAnswered = true;
    const isBn = this.lang === 'bn';
    const isCorrect = chosenIdx === qData.ans;

    if (isCorrect) this.score++;

    optButtons.forEach((btn, idx) => {
      btn.disabled = true;
      if (idx === qData.ans) {
        btn.classList.add('correct');
      } else if (idx === chosenIdx) {
        btn.classList.add('wrong');
      }
    });

    const factBox = this.container.querySelector('.trivia-fact-box');
    const actions = this.container.querySelector('.trivia-actions');

    factBox.hidden = false;
    factBox.className = `trivia-fact-box ${isCorrect ? 'fact-correct' : 'fact-wrong'}`;
    factBox.innerHTML = `
      <div class="fact-title">${isCorrect ? (isBn ? '✓ সঠিক উত্তর!' : '✓ Correct!') : (isBn ? '✗ ভুল উত্তর' : '✗ Incorrect')}</div>
      <p>${isBn ? qData.factBn : qData.factEn}</p>
    `;

    actions.hidden = false;
  }

  renderResult() {
    if (!this.container) return;
    const isBn = this.lang === 'bn';
    const total = this.currentQuestions.length;

    let badge = "";
    if (this.score === 5) {
      badge = isBn ? "👑 খাঁটি শিকড়ের রাজা (Heritage Grandmaster)" : "👑 Heritage Grandmaster (5/5)";
    } else if (this.score >= 3) {
      badge = isBn ? "🌟 বাংলার রসিক খাদ্যপ্রেমী (Culinary Connoisseur)" : "🌟 Culinary Connoisseur";
    } else {
      badge = isBn ? "🌱 শিকড়ের শিক্ষার্থী (Curious Explorer)" : "🌱 Curious Explorer";
    }

    this.container.innerHTML = `
      <div class="trivia-box result">
        <div class="trivia-result-icon">🎉</div>
        <h3>${isBn ? 'কুইজ সম্পন্ন হয়েছে!' : 'Quiz Completed!'}</h3>
        <div class="trivia-final-score">${this.score} / ${total}</div>
        <div class="trivia-result-badge">${badge}</div>
        <p>${isBn 
          ? 'বাংলাদেশের খাবার আর সংস্কৃতির প্রতিটি জেলার রয়েছে আপন অহংকার। আপনার টেস্ট ম্যাপে দাগ দিন এবং বন্ধুদের সাথে শেয়ার করুন!' 
          : 'Every district in Bangladesh has authentic culinary treasures. Keep exploring your roots on the map!'}</p>
        <button type="button" class="btn-trivia-start">${isBn ? 'আবার কুইজ দিন ↺' : 'Play Again ↺'}</button>
      </div>
    `;

    this.container.querySelector('.btn-trivia-start').addEventListener('click', () => this.start());
  }
}
